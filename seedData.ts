export function createInitialAttendance(ownerId = 'demo-owner'): AttendanceRecord[] {
  const dates = ['2026-11-20', '2026-11-22', '2026-11-25'];
  const students = createInitialStudents(ownerId);
  const records: AttendanceRecord[] = [];

  dates.forEach((date, dIdx) => {
    students.forEach((s, sIdx) => {
      // Leave 2026-11-25 partially marked or cleanly marked for realism
      let status: 'Present' | 'Absent' | 'Late' = 'Present';
      if ((dIdx + sIdx) % 7 === 0) status = 'Absent';
      else if ((dIdx + sIdx) % 5 === 0) status = 'Late';

      records.push({
        id: `${date}_${s.id}`,
        date,
        month: date.slice(0, 7),
        studentId: s.id,
        studentName: s.fullName,
        rollNumber: s.rollNumber,
        batchId: s.batchId,
        status,
        note: status === 'Late' ? 'Arrived 10 mins after bow-in' : '',
        ownerId,
      });
    });
  });

  return records;
}
